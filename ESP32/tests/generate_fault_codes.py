"""Generate/verify HMI fault dictionary and docs from the firmware registry.
Author: R.E. van Eekelen.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def outputs():
    registry = (ROOT/'ESP32/include/FaultCodeRegistry.h').read_text()
    source = (ROOT/'ESP32/include/StateMachine.h').read_text()
    rows = re.findall(r'\b(FAULT|INTERLOCK)\((\w+),\s*0x([0-9a-fA-F]+),\s*"([^"]+)"\)', registry)
    reasons = set(re.findall(r'^\s*(FAULT_\w+)\s*[,\n]', source, re.M))
    bits = {name: 1 << int(shift) for name, shift in re.findall(r'(\w+)\s*=\s*1u\s*<<\s*(\d+)', source)
            if name.startswith(('SAFETY_', 'DIGITAL_', 'VFD_FEEDBACK_', 'CONTACTOR_'))}
    assert {name for kind, name, _, _ in rows if kind == 'FAULT'} == reasons
    assert {name for kind, name, _, _ in rows if kind == 'INTERLOCK'} == set(bits)
    assert len({int(code, 16) for _, _, code, _ in rows}) == len(rows)
    dictionary = {code.upper(): {'kind': kind, 'name': name, 'description': description,
                                **({'mask': bits[name]} if kind == 'INTERLOCK' else {})}
                  for kind, name, code, description in rows}
    state_enum = re.search(r'typedef enum\s*\{([^}]+)\}\s*SystemState_t;', source).group(1)
    states = re.findall(r'\bSTATE_(\w+)', state_enum)
    dictionary = {'_states': states, **dictionary}
    doc = '# Fault codes\n\nGenerated by `ESP32/tests/generate_fault_codes.py`; do not edit codes here.\n\n'
    doc += 'Codes are stable hexadecimal identifiers, independent of enum ordering. For combined interlocks, the lowest defined bit selects the primary code; the full mask is retained and decoded. Unknown bits are displayed explicitly.\n\n'
    doc += '| Code | Existing reason | Interlock mask | Description |\n| --- | --- | --- | --- |\n'
    for kind, name, code, description in rows:
        mask = f'`0x{bits[name]:04X}`' if kind == 'INTERLOCK' else '—'
        doc += f'| `{code.upper()}` | `{name}` | {mask} | {description} |\n'
    doc += '\n`0302` means stale data or invalid timestamp ordering. Records retain decision time, snapshot time/sequence, raw unsigned age, timeout, validity, previous state and actual mode. A future age is marked INVALID, never clamped or accepted.\n\n'
    doc += 'Serial: `FAULT?` reads the latched first cause; `FAULT HISTORY` reads the 32-entry overwrite history; `FAULT DETAIL` prints the captured full snapshot on demand if it still matches that episode. Default output is one compact line per fault transition. Emergency-stop escalation appends an event without replacing the first cause. RESET archives the episode; it does not authorize START.\n\n'
    doc += 'Wire: `FAULT seq=... t=... code=0302 detail=0002 prev=2 mode=1 tick=... age=... timeout=100 safety_seq=... flags=... reason=9`. `prev` follows the existing state enum; mode 1 is MANUAL, 0 AUTO. Flag bit 0 means safety valid; bit 1 means the unsigned age is in the valid half-range. All other numeric fields are decimal except code/detail (hexadecimal). The ring and latch are RAM-only and reset at boot.\n'
    return {ROOT/'HMI/backend/fault_codes.json': json.dumps(dictionary, indent=2)+'\n',
            ROOT/'docs/FAULT_CODES.md': doc}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    for path, text in outputs().items():
        if options.check:
            if path.read_text(encoding='utf-8') != text:
                raise SystemExit('Fault dictionary/documentation drift: '+str(path))
        else:
            path.write_text(text, encoding='utf-8')
    print('PASS complete unique fault/interlock registry and generated documentation/HMI dictionary')


if __name__ == '__main__':
    main()
